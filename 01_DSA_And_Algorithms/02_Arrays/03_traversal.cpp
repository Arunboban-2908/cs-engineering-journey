#include <iostream>
using namespace std;
int main(){
    int arr[5] = {10, 20, 30, 40, 50};
    for (int i = 0; i < 5; i++){
        cout << arr[i] << endl;
    }
    return 0;
}

/*
Topic: Array Traversal

Traversal means visiting each element of an array.
A for loop can be used to visit elements from index 0
to the last index and perform an operation on each element.
*/